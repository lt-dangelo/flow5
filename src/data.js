export const DIFFICULTIES = ['beginner','intermediate'];
export function presetIds(presetId,difficulty='beginner'){
 const preset=PRESET_BY_ID[presetId];
 if(!preset||!DIFFICULTIES.includes(difficulty))throw new Error('Invalid preset or difficulty');
 return difficulty==='intermediate'?preset.intermediateIds:preset.ids;
}
